import { useEffect, useRef, useState } from 'react';
import * as THREE from 'three';
import { OrbitControls } from 'three/examples/jsm/controls/OrbitControls.js';
import { useLayout } from '../state/layoutStore';
import { useMasterPlan } from '../state/masterPlanStore';
import { buildMassingScene } from '../engine/export/glb';
import { bboxOfMulti, bboxUnion } from '../engine/geom/planar';
import type { Bbox } from '../engine/geom/types';
import { useEditedSite } from '../state/useEditedSite';
import { useSite } from '../state/store';
import { useActiveStorm } from '../state/hydrologyStore';
import { useAnalysisForViews, usePlanning } from '../state/planningStore';
import { buildTerrainOverlay } from './layerOverlay';
import { buildRaster } from './raster';
import { useRules } from '../state/useRules';
import { pick } from '../engine/data/config';
import { usePresent } from '../state/presentStore';
import { zoneColour } from './draw';
import { zoneHex } from './presentKit';
import { draftZonesFor } from '../engine/pipeline/basis';
import { useWalk } from '../state/walkStore';

/** Walk mode (owner 9 Oct): eye height on the ground, walking and running speeds. */
const EYE_M = 1.7;
const WALK_MS = 4;
const RUN_MS = 12;

/**
 * 3D terrain and massing. The same scene the GLB export writes, so what is on
 * screen is what lands in Rhino.
 */
export default function ThreeView(): React.ReactElement {
  const wrapRef = useRef<HTMLDivElement>(null);
  const cameraStateRef = useRef<{ pos: THREE.Vector3; target: THREE.Vector3 } | null>(null);
  // The walker: where it stands and looks, kept across scene rebuilds (a new plan, a new step).
  const walkerRef = useRef<{ x: number; z: number; yaw: number; pitch: number } | null>(null);
  const walking = useWalk((s) => s.walking);
  const setWalking = useWalk((s) => s.setWalking);
  const hudRef = useRef<HTMLSpanElement>(null);
  const [hintOn, setHintOn] = useState(false);
  useEffect(() => {
    if (!walking) return;
    setHintOn(true);
    const t = setTimeout(() => setHintOn(false), 4000);
    return () => clearTimeout(t);
  }, [walking]);
  const site = useEditedSite();
  const byZone = useLayout((s) => s.byZone);
  const activeIndex = useLayout((s) => s.activeOptionIndex);
  const plan = useMasterPlan((s) => s.plan);
  const rasterMode = useSite((s) => s.raster);
  // The storm the water is drawn for: the one the Hydrology panel reports.
  const active = useActiveStorm();
  const water = rasterMode === 'hydrology' && active && 'natural' in active ? active : null;
  const analysis = useAnalysisForViews();
  const planningVisible = usePlanning((s) => s.visible);
  const pipelinePlan = usePlanning((s) => s.plan);
  const planVisible = usePlanning((s) => s.planVisible);
  const villaMasses = usePlanning((s) => s.villaMasses);
  const presenting = usePresent((s) => s.active);
  const presentPlan = usePresent((s) => s.plans[s.option]);
  // The plan whose zoning the presentation shows: the option on screen (its plan may not be drawn yet).
  const zoningPlan = presentPlan ?? pipelinePlan;
  const zonesOn = useSite((s) => s.layers.zones);
  const rules = useRules();
  const unbuildableSlope = pick<number>(rules?.kmbr, 'rule22_site_suitability.no_building_slope_deg_over', 45);

  useEffect(() => {
    const wrap = wrapRef.current;
    if (!wrap || !site) return;

    // A master plan run is the whole site, so it wins over whatever single
    // zones were generated by hand before it.
    // Presenting shows the pipeline alone, not the older engine's layouts.
    const layouts = presenting
      ? []
      : plan
      ? plan.zones
          .map((z) => z.options[z.chosenIndex])
          .filter((o): o is NonNullable<typeof o> => Boolean(o))
      : Object.values(byZone)
          .map((options) => options[Math.min(activeIndex, options.length - 1)])
          .filter((o): o is NonNullable<typeof o> => Boolean(o));

    const scene = buildMassingScene({
      dem: site.dem,
      filled: site.filled ?? undefined,
      layouts,
      parcel: site.parcel,
      terrainStep: 4,
      tin: site.tin ?? undefined,
      water: water ? { model: water.model, storm: water.natural } : undefined,
      // The Site panel's terrain raster, draped as in 2D. Hydrology draws its
      // own water surfaces and flow lines instead.
      overlay:
        buildTerrainOverlay(
          site.dem,
          rasterMode !== 'none' && rasterMode !== 'hydrology'
            ? buildRaster(site.dem, rasterMode, unbuildableSlope)?.canvas ?? null
            : null,
          analysis,
          planningVisible,
          pipelinePlan,
          planVisible,
          presenting && zonesOn
            ? zoningPlan?.option.basis === 'draft_model'
              ? // Owner 12 Oct: the option's own zoning (optimised, with its pockets or link), coloured by use.
                draftZonesFor(site, zoningPlan.option.zoning ?? 'model', zoningPlan.option.roads)
                  .filter((z) => z.geom.length > 0)
                  .map((z) => ({ geom: z.geom, colour: zoneHex(z) }))
              : site.zones.filter((z) => z.geom.length > 0).map((z) => ({ geom: z.geom, colour: zoneColour(z.name) }))
            : [],
        ) ?? undefined,
      plan: pipelinePlan && planVisible.includes('buildings') ? pipelinePlan : undefined,
      planVillas: villaMasses,
    });
    scene.background = new THREE.Color(0x0f1518);
    scene.fog = new THREE.Fog(0x0f1518, 900, 2400);

    const hemi = new THREE.HemisphereLight(0xbcd3dd, 0x2a3338, 1.1);
    scene.add(hemi);
    const sun = new THREE.DirectionalLight(0xfff3e0, 1.5);
    // Kerala: the sun is high and a little south of overhead.
    sun.position.set(-300, 700, 450);
    scene.add(sun);

    const renderer = new THREE.WebGLRenderer({ antialias: true });
    renderer.setPixelRatio(Math.min(2, window.devicePixelRatio || 1));
    renderer.setSize(wrap.clientWidth, wrap.clientHeight);
    wrap.appendChild(renderer.domElement);

    const camera = new THREE.PerspectiveCamera(45, wrap.clientWidth / wrap.clientHeight, 1, 6000);
    // Presenting, the presenter's bar covers the foot of the screen: the picture sits higher.
    const lift = (): void => {
      // Presenting, the picture sits higher above the presenter's bar; walking, the bar is hidden: the horizon is centred.
      if (presenting && !useWalk.getState().walking) camera.setViewOffset(wrap.clientWidth, wrap.clientHeight, 0, wrap.clientHeight * 0.14, wrap.clientWidth, wrap.clientHeight);
      else camera.clearViewOffset();
    };
    lift();
    // Frame what has been generated; fall back to the whole parcel when there
    // is nothing to look at yet.
    const b: Bbox = layouts.length
      ? layouts
          .map((l) => bboxOfMulti(l.buildable))
          .reduce((acc, box) => bboxUnion(acc, box))
      : bboxOfMulti(site.parcel);
    const centreRl = site.dem.sampleBilinear([(b.minX + b.maxX) / 2, (b.minY + b.maxY) / 2]);
    const centre = new THREE.Vector3(
      (b.minX + b.maxX) / 2,
      Number.isFinite(centreRl) ? centreRl : 100,
      -(b.minY + b.maxY) / 2,
    );
    const span = Math.max(b.maxX - b.minX, b.maxY - b.minY);
    const controls = new OrbitControls(camera, renderer.domElement);
    if (cameraStateRef.current) {
      camera.position.copy(cameraStateRef.current.pos);
      controls.target.copy(cameraStateRef.current.target);
    } else {
      camera.position.set(centre.x - span * 0.5, centre.y + span * 0.55, centre.z + span * 0.75);
      controls.target.copy(centre);
    }
    controls.enableDamping = true;
    controls.maxPolarAngle = Math.PI / 2.05;
    controls.update();

    // ---- walk mode: eye height over the drawn terrain, the keys to move, a drag to look, double-click to jump
    const terrainMesh = scene.getObjectByName('Terrain');
    const solids = scene.getObjectByName('Masterplan');
    const down = new THREE.Raycaster();
    const ahead = new THREE.Raycaster();
    const groundAt = (x: number, z: number): number => {
      if (terrainMesh) {
        down.set(new THREE.Vector3(x, 2000, z), new THREE.Vector3(0, -1, 0));
        const hit = down.intersectObject(terrainMesh, false)[0];
        if (hit) return hit.point.y;
      }
      const v = site.dem.sampleBilinear([x, -z]);
      return Number.isFinite(v) ? v : Number.NaN;
    };
    const keys = new Set<string>();
    let orbitSaved: { pos: THREE.Vector3; target: THREE.Vector3 } | null = null;
    const enterWalk = (): void => {
      orbitSaved = { pos: camera.position.clone(), target: controls.target.clone() };
      if (!walkerRef.current) {
        // Start on the road nearest where the orbit was looking, facing along it (not inside a building); with no
        // roads drawn, where the orbit was looking, facing the way the camera faced.
        const dir = controls.target.clone().sub(camera.position);
        walkerRef.current = { x: controls.target.x, z: controls.target.z, yaw: Math.atan2(-dir.x, -dir.z), pitch: -0.05 };
        let best = Infinity;
        for (const r of pipelinePlan?.roads ?? []) {
          const c = r.centreline;
          for (let k = 0; k + 1 < c.length; k += 1) {
            const [ax, ay] = c[k]!;
            const [bx, by] = c[k + 1]!;
            const d = Math.hypot(ax - controls.target.x, -ay - controls.target.z);
            if (d < best && Math.hypot(bx - ax, by - ay) > 1) {
              best = d;
              // facing along the road: scene z is minus the plan's y
              walkerRef.current = { x: ax, z: -ay, yaw: Math.atan2(-(bx - ax), by - ay), pitch: -0.05 };
            }
          }
        }
      }
      controls.enabled = false;
      camera.near = 0.1;
      lift();
      camera.updateProjectionMatrix();
      // Daylight at eye level: a sky and a haze instead of the plan view's dark backdrop.
      scene.background = new THREE.Color(0xc9dbe6);
      scene.fog = new THREE.Fog(0xc9dbe6, 250, 1400);
      document.body.style.userSelect = 'none';
    };
    const leaveWalk = (): void => {
      controls.enabled = true;
      camera.near = 1;
      lift();
      camera.updateProjectionMatrix();
      scene.background = new THREE.Color(0x0f1518);
      scene.fog = new THREE.Fog(0x0f1518, 900, 2400);
      document.body.style.userSelect = '';
      if (orbitSaved) {
        camera.position.copy(orbitSaved.pos);
        controls.target.copy(orbitSaved.target);
      }
      keys.clear();
    };
    if (useWalk.getState().walking) enterWalk();
    const unsub = useWalk.subscribe((st, prev) => {
      if (st.walking && !prev.walking) enterWalk();
      else if (!st.walking && prev.walking) leaveWalk();
    });
    const onKeyDown = (e: KeyboardEvent): void => {
      if (!useWalk.getState().walking) return;
      const t = e.target as HTMLElement | null;
      if (t && (t.tagName === 'INPUT' || t.tagName === 'TEXTAREA' || t.tagName === 'SELECT')) return;
      if (e.key === 'Escape') {
        useWalk.getState().setWalking(false);
        return;
      }
      if (e.code.startsWith('Arrow') || e.code === 'Space') e.preventDefault();
      keys.add(e.code);
    };
    const onKeyUp = (e: KeyboardEvent): void => {
      keys.delete(e.code);
    };
    let drag: { x: number; y: number } | null = null;
    const onDown = (e: PointerEvent): void => {
      if (!useWalk.getState().walking) return;
      e.preventDefault(); // a drag looks round; it must not select the page's text
      drag = { x: e.clientX, y: e.clientY };
    };
    const onMove = (e: PointerEvent): void => {
      const w = walkerRef.current;
      if (!drag || !w || !useWalk.getState().walking) return;
      w.yaw -= (e.clientX - drag.x) * 0.004;
      w.pitch = Math.max(-1.3, Math.min(1.3, w.pitch - (e.clientY - drag.y) * 0.004));
      drag = { x: e.clientX, y: e.clientY };
    };
    const onUp = (): void => {
      drag = null;
    };
    const onDbl = (e: MouseEvent): void => {
      const w = walkerRef.current;
      if (!w || !useWalk.getState().walking || !terrainMesh) return;
      const r = renderer.domElement.getBoundingClientRect();
      const ray = new THREE.Raycaster();
      ray.setFromCamera(new THREE.Vector2(((e.clientX - r.left) / r.width) * 2 - 1, -((e.clientY - r.top) / r.height) * 2 + 1), camera);
      const hit = ray.intersectObject(terrainMesh, false)[0];
      if (hit) {
        w.x = hit.point.x;
        w.z = hit.point.z;
      }
    };
    window.addEventListener('keydown', onKeyDown);
    window.addEventListener('keyup', onKeyUp);
    renderer.domElement.addEventListener('pointerdown', onDown);
    window.addEventListener('pointermove', onMove);
    window.addEventListener('pointerup', onUp);
    renderer.domElement.addEventListener('dblclick', onDbl);
    const clock = new THREE.Clock();
    const blocked = (x: number, z: number, dx: number, dz: number, y: number): boolean => {
      if (!solids) return false;
      const len = Math.hypot(dx, dz);
      if (len < 1e-6) return false;
      // A wall within half a metre of the next step, at knee and at chest height.
      for (const h of [0.6, 1.4]) {
        ahead.set(new THREE.Vector3(x, y + h, z), new THREE.Vector3(dx / len, 0, dz / len));
        ahead.far = len + 0.5;
        if (ahead.intersectObject(solids, true).length > 0) return true;
      }
      return false;
    };
    const walkStep = (): void => {
      const w = walkerRef.current;
      const dt = Math.min(0.1, clock.getDelta());
      if (!w || !useWalk.getState().walking) return;
      if (keys.has('KeyQ')) w.yaw += 1.6 * dt;
      if (keys.has('KeyE')) w.yaw -= 1.6 * dt;
      const fwd = (keys.has('KeyW') || keys.has('ArrowUp') ? 1 : 0) - (keys.has('KeyS') || keys.has('ArrowDown') ? 1 : 0);
      const side = (keys.has('KeyD') || keys.has('ArrowRight') ? 1 : 0) - (keys.has('KeyA') || keys.has('ArrowLeft') ? 1 : 0);
      const speed = (keys.has('ShiftLeft') || keys.has('ShiftRight') ? RUN_MS : WALK_MS) * dt;
      const g0 = groundAt(w.x, w.z);
      if (fwd !== 0 || side !== 0) {
        const n = Math.hypot(fwd, side);
        const fx = -Math.sin(w.yaw);
        const fz = -Math.cos(w.yaw);
        const dx = ((fx * fwd - fz * side) / n) * speed;
        const dz = ((fz * fwd + fx * side) / n) * speed;
        // Slide along a wall: try the whole step, then each axis on its own. Never off the surveyed ground.
        for (const [mx, mz] of [[dx, dz], [dx, 0], [0, dz]] as const) {
          if (Number.isFinite(groundAt(w.x + mx, w.z + mz)) && !blocked(w.x, w.z, mx, mz, Number.isFinite(g0) ? g0 : 0)) {
            w.x += mx;
            w.z += mz;
            break;
          }
        }
      }
      const g = groundAt(w.x, w.z);
      const eye = (Number.isFinite(g) ? g : camera.position.y - EYE_M) + EYE_M;
      camera.position.set(w.x, eye, w.z);
      const look = new THREE.Vector3(-Math.sin(w.yaw) * Math.cos(w.pitch), Math.sin(w.pitch), -Math.cos(w.yaw) * Math.cos(w.pitch));
      camera.lookAt(camera.position.clone().add(look));
      if (hudRef.current) {
        const deg = ((((-w.yaw * 180) / Math.PI) % 360) + 360) % 360;
        const dirs = ['N', 'NE', 'E', 'SE', 'S', 'SW', 'W', 'NW'];
        hudRef.current.textContent = `ground RL ${Number.isFinite(g) ? g.toFixed(1) : '—'} · facing ${dirs[Math.round(deg / 45) % 8]}`;
      }
    };

    // Water particles: drops that follow the same receivers, on the same
    // flooded surface, as the flow lines. They start on the channels this
    // storm runs and leave where the water leaves the site.
    let sim: {
      receiver: Int32Array;
      level: Float32Array;
      spawn: number[];
      particles: { k: number; progress: number; speed: number }[];
      points: THREE.Points;
    } | null = null;

    if (water) {
      const { receiver, filledLevel } = water.model;
      const { channel } = water.natural;
      const spawn: number[] = [];
      for (let k = 0; k < channel.length; k += 1) {
        if (channel[k] === 1 && receiver[k]! >= 0) spawn.push(k);
      }
      if (spawn.length > 0) {
        const count = Math.min(15000, spawn.length * 4);
        const positions = new Float32Array(count * 3);
        const colors = new Float32Array(count * 3);
        const particles = [];
        for (let p = 0; p < count; p += 1) {
          particles.push({
            k: spawn[Math.floor(Math.random() * spawn.length)]!,
            progress: Math.random(),
            speed: 0.015 + Math.random() * 0.04,
          });
          colors[p * 3] = 0.2;
          colors[p * 3 + 1] = 0.75;
          colors[p * 3 + 2] = 1.0;
        }
        const geo = new THREE.BufferGeometry();
        geo.setAttribute('position', new THREE.BufferAttribute(positions, 3));
        geo.setAttribute('color', new THREE.BufferAttribute(colors, 3));
        const points = new THREE.Points(
          geo,
          new THREE.PointsMaterial({ size: 2.5, vertexColors: true, transparent: true, opacity: 0.85, sizeAttenuation: true }),
        );
        points.position.y = 1.0; // just above the surface
        scene.add(points);
        sim = { receiver, level: filledLevel, spawn, particles, points };
      }
    }

    const { nx, x0, y0, cell_m } = site.dem.meta;

    let frame = 0;
    const tick = (): void => {
      frame = requestAnimationFrame(tick);

      if (sim) {
        const positions = sim.points.geometry.attributes.position!.array as Float32Array;
        for (let p = 0; p < sim.particles.length; p += 1) {
          const d = sim.particles[p]!;
          d.progress += d.speed;
          if (d.progress >= 1) {
            const next = sim.receiver[d.k]!;
            d.progress -= 1;
            // Water that reaches the survey edge has left: start a new drop.
            d.k = next >= 0 ? next : sim.spawn[Math.floor(Math.random() * sim.spawn.length)]!;
          }
          const next = sim.receiver[d.k]!;
          if (next < 0) continue;
          const i1 = d.k % nx;
          const j1 = (d.k - i1) / nx;
          const i2 = next % nx;
          const j2 = (next - i2) / nx;
          const z1 = sim.level[d.k]!;
          const z2 = sim.level[next]!;
          const px1 = x0 + cell_m * (i1 + 0.5);
          const pz1 = -(y0 + cell_m * (j1 + 0.5));
          const px2 = x0 + cell_m * (i2 + 0.5);
          const pz2 = -(y0 + cell_m * (j2 + 0.5));
          positions[p * 3] = px1 + (px2 - px1) * d.progress;
          positions[p * 3 + 1] = z1 + (z2 - z1) * d.progress;
          positions[p * 3 + 2] = pz1 + (pz2 - pz1) * d.progress;
        }
        sim.points.geometry.attributes.position!.needsUpdate = true;
      }

      if (useWalk.getState().walking) walkStep();
      else {
        clock.getDelta();
        controls.update();
      }
      renderer.render(scene, camera);
    };
    tick();

    const resize = (): void => {
      camera.aspect = wrap.clientWidth / wrap.clientHeight;
      lift();
      camera.updateProjectionMatrix();
      renderer.setSize(wrap.clientWidth, wrap.clientHeight);
    };
    const ro = new ResizeObserver(resize);
    ro.observe(wrap);

    return () => {
      cameraStateRef.current = useWalk.getState().walking && orbitSaved
        ? orbitSaved
        : { pos: camera.position.clone(), target: controls.target.clone() };
      unsub();
      window.removeEventListener('keydown', onKeyDown);
      window.removeEventListener('keyup', onKeyUp);
      renderer.domElement.removeEventListener('pointerdown', onDown);
      window.removeEventListener('pointermove', onMove);
      window.removeEventListener('pointerup', onUp);
      renderer.domElement.removeEventListener('dblclick', onDbl);
      cancelAnimationFrame(frame);
      ro.disconnect();
      controls.dispose();
      renderer.dispose();
      scene.traverse((obj) => {
        if (obj instanceof THREE.Mesh || obj instanceof THREE.Points || obj instanceof THREE.LineSegments) {
          obj.geometry.dispose();
          const material = obj.material;
          if (Array.isArray(material)) material.forEach((m) => m.dispose());
          else material.dispose();
        }
      });
      if (wrap.contains(renderer.domElement)) {
        wrap.removeChild(renderer.domElement);
      }
    };
  }, [
    site,
    byZone,
    activeIndex,
    plan,
    rasterMode,
    water,
    analysis,
    planningVisible,
    unbuildableSlope,
    pipelinePlan,
    planVisible,
    villaMasses,
    presenting,
    zonesOn,
    zoningPlan,
  ]);

  return (
    <div ref={wrapRef} className={`relative h-full w-full bg-ink ${walking ? 'select-none' : ''}`}>
      {!walking && (
        <button
          type="button"
          onClick={() => setWalking(true)}
          title="Walk the site at eye height: W A S D or the arrows to move, drag to look, Shift to run, double-click to jump there, Esc to stop"
          className="absolute bottom-3 right-3 z-40 rounded-md border border-line bg-panel/90 px-2.5 py-1 text-[11px] font-semibold text-muted hover:text-fg"
        >
          🚶 Walk
        </button>
      )}
      {walking ? (
        // Nothing but the view (owner 9 Oct): the keys show for a few seconds on entering, then fade out.
        <div
          className={`pointer-events-none absolute bottom-6 left-1/2 z-40 -translate-x-1/2 rounded-md bg-black/45 px-3 py-1.5 text-center text-[11px] text-white/85 transition-opacity duration-1000 ${
            hintOn ? 'opacity-100' : 'opacity-0'
          }`}
        >
          W A S D or arrows to move · drag to look · Shift to run · double-click to jump · Esc to leave
        </div>
      ) : (
        <div className="pointer-events-none absolute bottom-3 left-3 rounded border border-line bg-panel/90 px-2 py-1 text-[11px] text-muted">
          Drag to orbit, scroll to zoom. Terrain is the 2 m DEM; unsurveyed ground is left open rather than filled.
          Levels are RL on the assumed TBM datum.
        </div>
      )}
    </div>
  );
}
